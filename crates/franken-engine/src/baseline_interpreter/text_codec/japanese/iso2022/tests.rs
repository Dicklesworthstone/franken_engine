fn units(bytes: &[u8], fatal: bool) -> Option<Vec<u16>> {
    DecodeState::default()
        .decode_slice("iso-2022-jp", bytes, fatal, false, false)
        .map(|value| value.code_units_vec())
}

#[test]
fn all_designations_and_both_labels_reach_native_decoding() {
    for label in ["iso-2022-jp", "csiso2022jp", " \tISO-2022-JP\r\n"] {
        assert_eq!(super::super::super::canonical_decoder_encoding(label), Some("iso-2022-jp"));
    }
    assert_eq!(super::super::super::canonical_decoder_encoding("\u{a0}iso-2022-jp"), None);
    for (bytes, expected) in [
        (&b"plain\0\n\\~"[..], "plain\0\n\\~"),
        (&b"\x1b(J\\~\x1b(B\\~"[..], "¥‾\\~"),
        (&b"\x1b(I!_\x1b(B!"[..], "｡ﾟ!"),
        (&b"\x1b$BF|K\\\x1b(B"[..], "日本"),
        (&b"\x1b$@$\"\x1b(B"[..], "あ"),
        (&b"\x1b$B!A"[..], "～"),
    ] {
        let expected: Vec<_> = expected.encode_utf16().collect();
        assert_eq!(units(bytes, false), Some(expected.clone()));
        assert_eq!(units(bytes, true), Some(expected));
    }
}

#[test]
fn malformed_escapes_and_eof_recover_in_order() {
    for (bytes, expected) in [
        (&b"\x1b$X!"[..], "�$X!"),
        (&b"\x1b\""[..], "�\""),
        (&b"\x1b"[..], "�"),
        (&b"\x1b$"[..], "�$"),
        (&b"\x1b("[..], "�("),
        (&b"\x1b(B\x1b(J\\"[..], "�¥"),
        (&b"\x1b$B$\x1b(Bok"[..], "�ok"),
        (&b"\x1b$B$"[..], "�"),
        (&b"\x1b$B$\x20\x1b(B!"[..], "�!"),
        (&b"\x1b$B\x1b$"[..], "��"),
        (&b"\x0e\x0f\x80"[..], "���"),
        (&b"\x1b(I\x20\x60"[..], "��"),
    ] {
        assert_eq!(units(bytes, false), Some(expected.encode_utf16().collect()), "{bytes:?}");
        assert_eq!(units(bytes, true), None, "fatal {bytes:?}");
    }
}

#[test]
fn every_trailing_byte_and_escape_split_matches_whole_input_after_state_restore() {
    for prefix in [
        &b""[..], &b"\x1b"[..], &b"\x1b("[..], &b"\x1b$"[..],
        &b"\x1b(J"[..], &b"\x1b(I"[..], &b"\x1b$B"[..], &b"\x1b$B$"[..],
    ] {
        for first in 0..=u8::MAX {
            for second in 0..=u8::MAX {
                let mut input = prefix.to_vec();
                input.extend([first, second]);
                let expected = units(&input, false).unwrap();
                let mut saved = DecodeState::default();
                let mut actual = Vec::new();
                for byte in &input {
                    actual.extend(saved.decode_slice("iso-2022-jp", &[*byte], false, false, true).unwrap().code_units_vec());
                    assert!(saved.pack() >= 0 && saved.pack() < 1 << 28);
                    assert_eq!(saved.pending_len, 3);
                    assert_eq!(saved, DecodeState::unpack(saved.pack()));
                    saved = DecodeState::unpack(saved.pack());
                    let before = saved;
                    assert_eq!(saved.decode_slice("iso-2022-jp", &[], false, false, true), Some(JsString::from("")));
                    assert_eq!(saved, before, "empty chunks do not flush escapes or modes");
                }
                actual.extend(saved.decode_slice("iso-2022-jp", &[], false, false, false).unwrap().code_units_vec());
                assert_eq!(actual, expected, "{input:?}");
                assert_eq!(saved, DecodeState::default());
            }
        }
    }
}

#[test]
fn jis_pairs_use_the_existing_normative_index_without_eudc_or_jis0212() {
    // Compare all valid row/column encodings against the independent existing
    // EUC-JP route, not a table generated by the new designation machine.
    for lead in 0x21..=0x7e {
        for trail in 0x21..=0x7e {
            let encoded = [0x1b, 0x24, 0x42, lead, trail];
            for fatal in [false, true] {
                let expected = DecodeState::default()
                    .decode_slice("euc-jp", &[lead + 0x80, trail + 0x80], fatal, false, false)
                    .map(|text| text.code_units_vec());
                assert_eq!(units(&encoded, fatal), expected, "{encoded:?}");
            }
        }
    }
}

#[test]
fn decoder_lifetimes_do_not_leak_modes_or_incomplete_escapes() {
    let mut saved = DecodeState::default();
    assert_eq!(decode(&mut saved, b"\x1b(J", false, true), Some(JsString::from("")));
    assert_eq!(decode(&mut saved, b"\\", false, false), Some(JsString::from("¥")));
    assert_eq!(saved, DecodeState::default());
    assert_eq!(decode(&mut saved, b"\\", false, false), Some(JsString::from("\\")));
    for prefix in [&b"\x1b"[..], &b"\x1b$"[..], &b"\x1b$B$"[..]] {
        assert!(decode(&mut saved, prefix, true, true).is_some());
        assert!(decode(&mut saved, &[], true, false).is_none());
        assert_eq!(saved, DecodeState::default());
        assert_eq!(decode(&mut saved, b"ok", true, false), Some(JsString::from("ok")));
    }
    // Existing engine policy, explicitly not WHATWG queue retention after
    // fatal streaming failure. Do not claim this reuse case as conformance.
    assert!(decode(&mut saved, b"\x1b(J", true, true).is_some());
    assert!(decode(&mut saved, &[0xff, 0x5c], true, true).is_none());
    assert_eq!(saved, DecodeState::default());
}

#[test]
fn corrupt_restored_state_is_rejected_before_lead_arithmetic() {
    for pending in [[7, 0, 0], [0, 4, 0], [TRAIL, ASCII, 0x21], [TRAIL, LEAD, 0],
        [TRAIL, LEAD | 0x80, 0x21], [ESCAPE, ASCII, 0], [ESCAPE_START, ASCII, 1],
        [ASCII, ROMAN, 0], [LEAD, LEAD, 0x21]] {
        let mut saved = DecodeState { pending, pending_len: 3, bom_seen: false, streaming: true };
        assert!(decode(&mut saved, b"A", false, true).is_none());
        assert_eq!(saved, DecodeState::default());
    }
    for pending_len in [0, 1, 2, 4, usize::MAX] {
        let mut saved = DecodeState { pending: [ESCAPE, 0, 0x24], pending_len, bom_seen: false, streaming: true };
        assert!(decode(&mut saved, b"A", false, false).is_none());
        assert_eq!(saved, DecodeState::default());
    }
}

#[test]
fn mode_only_secret_prefix_retains_provenance_in_public_suffix_output() {
    let tree = crate::parser_api_stability::parse_script("0;").unwrap();
    let module = crate::lowering_pipeline::lower_ir0_to_ir3(
        &crate::ir_contract::Ir0Module::from_syntax_tree(tree, "iso2022-carry.js"),
        &crate::lowering_pipeline::LoweringContext::new("iso2022", "mode-carry", "builtin-only"),
    ).unwrap().ir3;
    for throughput in [false, true] {
        let mut config = if throughput { InterpreterConfig::v8_defaults() } else { InterpreterConfig::quickjs_defaults() };
        config.granted_capabilities = [RuntimeCapability::VmDispatch, RuntimeCapability::HeapAllocate, RuntimeCapability::Builtin].into_iter().collect();
        let mut core = InterpreterCore::new(config, "iso2022-mode-carry");
        core.seed_register(0, Value::str("iso-2022-jp")).unwrap();
        let decoder = core.construct_text_decoder(None, RegRange { start: 0, count: 1 }).unwrap();
        let Value::Object(id) = decoder else { panic!("decoder object") };
        let prefix = core.alloc_uint8_array_from_bytes(b"\x1b(J").unwrap();
        let options = core.alloc_object_with_properties(&[("stream", Value::Bool(true))]).unwrap();
        core.seed_register(0, Value::Object(prefix)).unwrap();
        core.seed_register(1, Value::Object(options)).unwrap();
        core.set_register_label(0, Label::Secret).unwrap();
        assert_eq!(core.text_codec_method("decode", decoder.clone(), RegRange { start: 0, count: 2 }).unwrap(), Value::str(""));
        assert_eq!(core.object_mutation_labels.get(&id), Some(&Label::Secret));
        let suffix = core.alloc_uint8_array_from_bytes(b"\\").unwrap();
        core.seed_register(0, Value::Object(suffix)).unwrap();
        core.set_register_label(0, Label::Public).unwrap();
        let method = core.get_v(&module, &decoder, &RuntimePropertyKey::String("decode".into())).unwrap();
        let (value, label) = core.invoke_inline_method_call_with_argument_label(Some(&module), method, decoder, vec![Value::Object(suffix)], None).unwrap();
        assert_eq!(value, Value::str("¥"));
        assert!(label >= Label::Secret);
        assert_eq!(core.heap[id.0 as usize].properties.get(super::super::super::DECODER_STATE_SLOT), Some(&Value::Int(0)));
        assert_eq!(core.estimated_memory_bytes(), core.recompute_estimated_memory_bytes());
    }
}
